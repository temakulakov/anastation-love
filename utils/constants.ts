export const formatDate = (dateStr: string): string => {
  const months: { [key: string]: string } = {
    '01': 'января',
    '02': 'февраля',
    '03': 'марта',
    '04': 'апреля',
    '05': 'мая',
    '06': 'июня',
    '07': 'июля',
    '08': 'августа',
    '09': 'сентября',
    '10': 'октября',
    '11': 'ноября',
    '12': 'декабря',
  };
  
  const [day, month, year] = dateStr.split('.');
  if (!day || !month || !year || !months[month]) return dateStr;
  return `${day} ${months[month]} ${year}`;
};

